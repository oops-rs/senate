#!/usr/bin/env bash
# Builds the Rust core (crates/senate-app-core) as a static library for the
# macOS app and generates its Swift bindings, into apps/macos/Generated/:
#
#   libsenate_app_core.a          universal (arm64 + x86_64) unless ARCHS says otherwise
#   senate_app_core.swift         the Swift API (compiled into the app)
#   senate_app_coreFFI.h          the C side (the app's bridging header includes it)
#   senate_app_coreFFI.modulemap
#
# Usage: scripts/build-core.sh [--release]
# Xcode runs it as a pre-build phase; there CONFIGURATION picks the profile
# and ARCHS the architectures (only the active one, in Debug).
set -euo pipefail

app_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
root="$(cd "$app_dir/../.." && pwd)"
out="$app_dir/Generated"
crate=senate-app-core
lib=libsenate_app_core.a

# Xcode's script environment has a minimal PATH.
export PATH="$HOME/.cargo/bin:/opt/homebrew/bin:/usr/local/bin:$PATH"
# The app's deployment target. It cannot go in MACOSX_DEPLOYMENT_TARGET
# (which Xcode exports): with rustc 1.97 on macOS 27 any value of it makes
# release-mode proc-macro dylibs fail to load ("mis-aligned LINKEDIT string
# pool"). Rust code keeps rustc's default (older, links fine); the C in the
# dependencies (sqlite, ring) gets it through per-target CFLAGS, else clang
# targets the SDK's version and ld warns.
min_macos=14.0
unset MACOSX_DEPLOYMENT_TARGET
export CFLAGS_aarch64_apple_darwin="-mmacosx-version-min=$min_macos"
export CFLAGS_x86_64_apple_darwin="-mmacosx-version-min=$min_macos"

profile=debug
if [[ "${1:-}" == "--release" || "${CONFIGURATION:-}" == "Release" ]]; then
  profile=release
fi
cargo_profile=()
if [[ $profile == release ]]; then
  cargo_profile=(--release)
fi

read -r -a archs <<< "${ARCHS:-arm64 x86_64}"
libs=()
for arch in "${archs[@]}"; do
  case "$arch" in
    arm64) triple=aarch64-apple-darwin ;;
    x86_64) triple=x86_64-apple-darwin ;;
    *) echo "build-core.sh: unsupported architecture $arch" >&2; exit 1 ;;
  esac
  echo "build-core.sh: cargo build -p $crate ($profile, $triple)"
  cargo build --manifest-path "$root/Cargo.toml" -p "$crate" --lib \
    --target "$triple" ${cargo_profile[@]+"${cargo_profile[@]}"}
  libs+=("$root/target/$triple/$profile/$lib")
done

mkdir -p "$out"
staged="$(mktemp -d)"
trap 'rm -rf "$staged"' EXIT

if [[ ${#libs[@]} -eq 1 ]]; then
  cp "${libs[0]}" "$staged/$lib"
else
  lipo -create "${libs[@]}" -output "$staged/$lib"
fi

# The bindings come from the library's own metadata, generated by the
# bindgen of the exact UniFFI version the library was built with.
cargo run --quiet --manifest-path "$root/Cargo.toml" -p "$crate" \
  --features bindgen --bin uniffi-bindgen -- \
  generate --library "${libs[0]}" --language swift --out-dir "$staged" >/dev/null

# Replace only what changed, so Xcode does not recompile the bindings or
# relink on every build.
for f in "$staged"/*; do
  name="$(basename "$f")"
  if ! cmp -s "$f" "$out/$name"; then
    cp "$f" "$out/$name"
  fi
done
echo "build-core.sh: wrote $out"
